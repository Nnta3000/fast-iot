"""
EN: **Arms experiment: does more than one observation help, at fixed feature family and Θ?**

    Arms, same data, same family, same Θ:

      `A_single`   fit θ on **one** plan; repeated for every plan of the cell; means and spreads over plans.
      `A_single_big`  arm A on **one** plan of `L·n` points (tells "more observations" from "more points").
      `B_averaged` fit each single-plan θ, then average them and renormalise onto Θ (the M-IOT synthetic baseline).
      `C_joint`    one shared θ on all `L` plans (the sparse bundle).
      `D_oracle`   the planted θ* (synthetic only).
      `E_neutral`  uniform θ.

    Every observation has its **own points and its own marginals**; the held-out evaluation uses a **fresh**
    instance (fresh points, fresh marginals, exact-OT plan at θ*), never a training observation.

    Readings (held-out): `agreement` (Σ min(P, P̂)/Σ P), `excess_cost` (⟨c*, P̂⟩/OT(c*) − 1), `cost_rel` (the fitted
    cost against c*, up to a positive scale — the only gauge the family leaves free, since it has no constant
    column), and in-sample `train_regret` with `train_feasible` (F ≤ tol, i.e. the exact LP's δ* ≥ 0). θ is recorded
    in every row; the spread across seeds and across single-plan fits is the empirical cone width.

    Controls: plans generated by a cost **outside** the family, and a **shuffled** target assignment used only by the
    fit. A reading counts only if the control moves it.

CN: **Arms 实验：在固定特征族与 Θ 下，多于一个观测是否有帮助？** 六个臂见上（A 单计划、A 大计划 `L·n` 点、B 平均、
C 联合、D oracle、E 中性）。每个观测有**自己的点与自己的 marginal**；留出评估用**全新**实例（新点、新 marginal、θ* 处的精确
OT 计划），从不使用训练观测。读数：`agreement`、`excess_cost`、`cost_rel`（到正缩放的代价误差 —— 族无常数列，故这是唯一
自由规范），以及样本内 `train_regret` 与 `train_feasible`（F ≤ tol，即精确 LP 的 δ* ≥ 0）。每行记录 θ；跨种子与跨单计划
拟合的离散度就是经验锥宽。对照：族外代价生成的计划、以及只被拟合使用的**打乱**目标指派。读数只有在对照移动时才算数。
"""

from __future__ import annotations

import argparse
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import ot
import scipy.sparse as sparse

from iot.sparse.bundle_multi import solve_bundle_multi
from iot.sparse.features import DistanceProfileFeatures
from iot.sparse.sparse_ot import solve_sparse_ot
from iot_experiments.harness.records import RunLog, RunRecord, format_table, summarise, write_records

OUT = Path("iot_experiments/out/multi_observation_sparse/arms")


def planted_theta(bumps: int) -> np.ndarray:
    """
    EN: a smooth planted profile over the bump basis: `theta*_k ∝ exp(-((c_k - 0.35)/0.25)^2)`.

        The same basis is used for generation and fitting, so the family always contains `c*`; `bumps` changes how
        many parameters must be pinned, not whether the truth is representable.

    CN: 鼓包基上的平滑植入剖面；生成与拟合用同一基，故族总含 `c*`，`bumps` 只改变需要钉住的参数个数。
    """
    centres = np.linspace(0.0, 1.0, int(bumps))
    weights = np.exp(-((centres - 0.35) / 0.25) ** 2)
    return weights / weights.sum()


def _marginals(n: int, mode: str, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """EN: uniform or random marginals with mass on every point. CN: 均匀或随机 marginal，每点有质量。"""
    if mode == "uniform":
        return np.full(n, 1.0 / n), np.full(n, 1.0 / n)
    source = rng.random(n) + 0.1
    target = rng.random(n) + 0.1
    return source / source.sum(), target / target.sum()


def _corrupt(plan: np.ndarray, fraction: float, rng: np.random.Generator) -> np.ndarray:
    """
    EN: swap partners between randomly chosen support edges, preserving both marginals.

        Pick two edges `(i,j)`, `(i',j')` with masses `m, m'`; take `δ = min(m, m') · u` with `u ~ U(0,1)` and move
        `δ` from `(i,j)→(i',j)` and `δ` from `(i',j')→(i,j)`. Row and column sums are unchanged exactly; for a
        uniform matching (`m = m' = 1/n`) it is a literal pair swap.

    CN: 在随机选取的支撑边上互换伙伴，同时保持两个 marginal。取两条边 `(i,j)`、`(i',j')`（质量 `m,m'`），
        `δ = min(m,m')·u`，把 `δ` 从 `(i,j)` 移到 `(i',j)`、把 `δ` 从 `(i',j')` 移到 `(i,j)`；行/列和精确不变。
        均匀匹配（`m=m'=1/n`）时就是字面上的成对互换。
    """
    out = np.array(plan, dtype=np.float64, copy=True)
    support = np.argwhere(out > 0.0)
    if support.size == 0 or fraction <= 0.0:
        return out
    swaps = max(1, int(round(float(fraction) * support.shape[0])))
    for _ in range(swaps):
        first, second = rng.integers(0, support.shape[0], size=2)
        i, j = support[first]
        i2, j2 = support[second]
        if (i, j) == (i2, j2) or j == j2 or i == i2:
            continue
        delta = min(out[i, j], out[i2, j2]) * float(rng.random())
        if delta <= 0.0:
            continue
        out[i, j] -= delta
        out[i2, j2] -= delta
        out[i, j2] += delta
        out[i2, j] += delta
    return out


def _observation(n: int, bumps: int, theta_star: np.ndarray, seed: int, window: int, *,
                 marginal_mode: str, noise: float, outside: bool, base_seed: int
                 ) -> tuple[DistanceProfileFeatures, sparse.csr_matrix]:
    """
    EN: one observation: fresh points, fresh marginals, exact-OT plan at θ* (optionally corrupted or out-of-family).

    CN: 一个观测：新点、新 marginal、θ* 处的精确 OT 计划（可加噪或改用族外代价）。
    """
    rng = np.random.default_rng((base_seed, seed, window))
    source_points = rng.random((n, 2))
    target_points = rng.random((n, 2))
    features = DistanceProfileFeatures(source_points, target_points, bumps=int(bumps), seed=base_seed)
    rows = np.repeat(np.arange(n, dtype=np.int64), n)
    cols = np.tile(np.arange(n, dtype=np.int64), n)
    cost = np.asarray(features.costs(theta_star, rows, cols)).reshape(n, n)
    if outside:
        noise_matrix = rng.random((n, n))
        cost = cost + 0.5 * (noise_matrix + noise_matrix.T)
    source_mass, target_mass = _marginals(n, marginal_mode, rng)
    plan = np.asarray(ot.emd(source_mass, target_mass, cost, numItermax=2_000_000))
    if noise > 0.0:
        plan = _corrupt(plan, float(noise), rng)
        plan = np.clip(plan, 0.0, None)
    return features, sparse.csr_matrix(plan)


def _value(theta: np.ndarray, maps: list[DistanceProfileFeatures], plans: list[sparse.csr_matrix],
           *, tol: float = 1e-9) -> float:
    """EN: the exact training objective `F(θ)` via the sparse oracle. CN: 用稀疏 oracle 计算精确训练目标。"""
    total = 0.0
    for features, plan in zip(maps, plans, strict=True):
        coo = plan.tocoo()
        phi = features.features(coo.row.astype(np.int64), coo.col.astype(np.int64))
        mass_source = np.asarray(plan.sum(axis=1)).reshape(-1)
        mass_target = np.asarray(plan.sum(axis=0)).reshape(-1)
        result = solve_sparse_ot(features, mass_source, mass_target, theta=theta, tol=tol)
        total += float(phi.T @ coo.data @ theta) - result.value
    return float(total)


@dataclass(frozen=True)
class Readings:
    """EN: the held-out readings of one arm. CN: 一个臂的留出读数。"""

    agreement: float
    excess_cost: float
    cost_rel: float


def _readings(theta: np.ndarray, planted: np.ndarray, held_features: DistanceProfileFeatures,
              held_plan: sparse.csr_matrix) -> Readings:
    """
    EN: evaluate a fitted θ on a **fresh** instance: fraction reproduced, excess cost under c*, and the cost error.

    CN: 在**全新**实例上评估拟合出的 θ：复现比例、c* 下的超出代价、以及代价误差。
    """
    n = int(held_features.n_source)
    rows = np.repeat(np.arange(n, dtype=np.int64), n)
    cols = np.tile(np.arange(n, dtype=np.int64), n)
    truth = np.asarray(held_features.costs(planted, rows, cols)).reshape(n, n)
    guess = np.asarray(held_features.costs(theta, rows, cols)).reshape(n, n)
    source_mass = np.asarray(held_plan.sum(axis=1)).reshape(-1)
    target_mass = np.asarray(held_plan.sum(axis=0)).reshape(-1)
    predicted = np.asarray(ot.emd(source_mass, target_mass, guess, numItermax=2_000_000))
    observed = held_plan.toarray()
    agreement = float(np.minimum(predicted, observed).sum() / observed.sum())
    optimum = float(ot.emd2(source_mass, target_mass, truth, numItermax=2_000_000))
    excess = float(np.sum(truth * predicted) / optimum - 1.0) if optimum > 0 else float("nan")
    scale = float(np.sum(guess * truth) / np.sum(guess ** 2)) if np.sum(guess ** 2) > 0 else 0.0
    cost_rel = float(np.linalg.norm(scale * guess - truth) / np.linalg.norm(truth))
    return Readings(agreement=agreement, excess_cost=excess, cost_rel=cost_rel)


def run_cell(log: RunLog, *, n: int, bumps: int, n_observations: int, noise: float, marginal_mode: str,
             seed: int, control: str, iterations: int = 40, one_big_plan: bool = False
             ) -> list[RunRecord]:
    """EN: one (n, K, L, p, marginal, seed, control) cell, all arms. CN: 一个格子的全部臂。"""
    planted = planted_theta(int(bumps))
    base_seed = 10_000 + int(seed)
    outside = control == "outside"
    observations = [_observation(n, bumps, planted, seed, window, marginal_mode=marginal_mode, noise=noise,
                                 outside=outside, base_seed=base_seed)
                    for window in range(int(n_observations))]
    if control == "shuffle":
        # EN: the fit sees a permuted target assignment; the plans were generated with the true one.
        # CN: 拟合看到的是打乱后的目标指派；计划仍由真实指派生成。
        rng = np.random.default_rng((base_seed, 99))
        shuffled = []
        for features, plan in observations:
            permutation = rng.permutation(int(features.n_target))
            shuffled.append((DistanceProfileFeatures(features.source_points,
                                                     features.target_points[permutation], bumps=int(bumps),
                                                     seed=base_seed), plan))
        observations = shuffled
    maps = [item[0] for item in observations]
    plans = [item[1] for item in observations]
    held_features, held_plan = _observation(n, bumps, planted, seed, 10_000,
                                            marginal_mode=marginal_mode, noise=0.0, outside=False,
                                            base_seed=base_seed)

    records: list[RunRecord] = []

    def add(arm: str, theta: np.ndarray, train_regret: float, extra: dict[str, object]) -> None:
        readings = _readings(theta, planted, held_features, held_plan)
        metrics = {"agreement": readings.agreement, "excess_cost": readings.excess_cost,
                   "cost_rel": readings.cost_rel, "train_regret": float(train_regret),
                   "train_feasible": float(train_regret <= 1e-8)}
        records.append(RunRecord(study="multi_observation_sparse", geometry=f"n{n}_K{bumps}_L{n_observations}"
                                 f"_p{noise:g}_{marginal_mode}_{control}_s{seed}", arm=arm, k=int(bumps),
                                 m=int(n), draw=int(seed), metrics=metrics,
                                 config={"n": n, "K": bumps, "L": n_observations, "noise": noise,
                                         "marginals": marginal_mode, "control": control, "seed": seed},
                                 extra={**extra, "theta": [float(v) for v in theta],
                                        "theta_star": [float(v) for v in planted]}))

    # EN: arm D and E are free.
    add("D_oracle", planted, 0.0, {})
    add("E_neutral", np.full(int(bumps), 1.0 / int(bumps)), _value(np.full(int(bumps), 1.0 / int(bumps)),
                                                                   maps, plans), {})

    # EN: arm C — one shared θ.
    joint = solve_bundle_multi(plans, maps, tol=1e-6, max_iterations=int(iterations), inner_tol=1e-9)
    add("C_joint", joint.theta, joint.value, {"gap": joint.gap, "n_cuts": joint.n_cuts})

    # EN: arm A — one θ per plan; arm B — their average.
    singles = [solve_bundle_multi([plan], [features], tol=1e-6, max_iterations=int(iterations), inner_tol=1e-9)
               for plan, features in zip(plans, maps, strict=True)]
    for position, single in enumerate(singles):
        add(f"A_single", single.theta, single.value, {"observation": position})
    averaged = np.mean(np.stack([np.asarray(single.theta) for single in singles], axis=0), axis=0)
    averaged = np.clip(averaged, 0.0, None)
    averaged = averaged / averaged.sum() if averaged.sum() > 0 else np.full(int(bumps), 1.0 / int(bumps))
    add("B_averaged", averaged, _value(averaged, maps, plans), {})

    # EN: arm A on ONE plan of L·n points (is more data in one observation the same as more observations?).
    # CN: 一个含 L·n 个点的单一计划上的 A 臂（"一个观测里更多点" 是否等同于 "更多观测"）。
    if one_big_plan:
        big_n = int(n_observations) * int(n)
        big_features, big_plan = _observation(big_n, bumps, planted, seed, 20_000, marginal_mode=marginal_mode,
                                              noise=noise, outside=outside, base_seed=base_seed)
        big = solve_bundle_multi([big_plan], [big_features], tol=1e-6, max_iterations=int(iterations),
                                 inner_tol=1e-9)
        readings = _readings(big.theta, planted, held_features, held_plan)
        records.append(RunRecord(
            study="multi_observation_sparse", geometry=f"n{n}_K{bumps}_L{n_observations}"
            f"_p{noise:g}_{marginal_mode}_{control}_s{seed}", arm="A_single_big", k=int(bumps), m=big_n,
            draw=int(seed),
            metrics={"agreement": readings.agreement, "excess_cost": readings.excess_cost,
                     "cost_rel": readings.cost_rel, "train_regret": big.value,
                     "train_feasible": float(big.value <= 1e-8)},
            config={"n": n, "K": bumps, "L": n_observations, "noise": noise, "marginals": marginal_mode,
                    "control": control, "seed": seed},
            extra={"theta": [float(v) for v in big.theta], "theta_star": [float(v) for v in planted],
                   "big_n": big_n}))
    return records


def main(argv: list[str] | None = None) -> int:
    """EN: entry point; `--pilot` runs one cell and prints its wall time. CN: 入口；`--pilot` 跑一个格子并打印耗时。"""
    parser = argparse.ArgumentParser(description="arms for the multi-observation regret")
    parser.add_argument("--ks", type=int, nargs="+", default=[10, 40, 80])
    parser.add_argument("--ls", type=int, nargs="+", default=[1, 2, 5, 10, 20, 50])
    parser.add_argument("--ps", type=float, nargs="+", default=[0.0, 0.05, 0.2])
    parser.add_argument("--marginals", nargs="+", default=["uniform", "random"])
    parser.add_argument("--controls", nargs="+", default=["none", "outside", "shuffle"])
    parser.add_argument("--seeds", type=int, nargs="+", default=list(range(10)))
    parser.add_argument("--n", type=int, default=40)
    parser.add_argument("--iterations", type=int, default=40)
    parser.add_argument("--one-big-plan", action="store_true")
    parser.add_argument("--pilot", action="store_true")
    parser.add_argument("--tag", default="pilot")
    args = parser.parse_args(list(argv) if argv is not None else None)

    out_dir = OUT / args.tag
    out_dir.mkdir(parents=True, exist_ok=True)
    log = RunLog(out_dir / "run.log")
    started = time.perf_counter()
    records: list[RunRecord] = []
    cells = 0
    grid = [(int(bumps), int(n_obs), float(noise), str(marginal), str(control), int(seed))
            for bumps in args.ks
            for n_obs in args.ls
            for noise in args.ps
            for marginal in args.marginals
            for control in args.controls
            for seed in args.seeds]
    if args.pilot:
        grid = grid[:1]
    for bumps, n_obs, noise, marginal, control, seed in grid:
        cell_started = time.perf_counter()
        records.extend(run_cell(log, n=int(args.n), bumps=bumps, n_observations=n_obs, noise=noise,
                                marginal_mode=marginal, seed=seed, control=control,
                                iterations=int(args.iterations), one_big_plan=bool(args.one_big_plan)))
        cells += 1
        log.line(f"cell K={bumps} L={n_obs} p={noise:g} {marginal} {control} s={seed}: "
                 f"{time.perf_counter() - cell_started:.1f}s")
    total = time.perf_counter() - started
    log.line(f"{cells} cells in {total:.1f}s ({total / max(1, cells):.2f}s per cell)")
    write_records(out_dir / "records.json", records,
                  provenance={"question": "does more than one observation pin theta better than one plan, at "
                                          "fixed family and Theta?",
                              "family": "DistanceProfileFeatures (bump basis, subsample-RMS norm, no constant / "
                                        "same-zone / mask column)",
                              "arms": "A_single (per plan, mean+spread), A_single_big (one plan of L*n points), "
                                      "B_averaged, C_joint (sparse bundle), D_oracle, E_neutral",
                              "held_out": "fresh points, fresh marginals, exact-OT plan at theta*; never a "
                                          "training observation",
                              "gauge": "positive cost scaling only (the family has no constant column); "
                                       "cost_rel uses the least-squares positive scale",
                              "controls": "plans from an out-of-family cost; shuffled target assignment for the "
                                          "fit only"})
    table = summarise(records, group=("arm",), metrics=("agreement", "excess_cost", "cost_rel", "train_regret"))
    log.line("\n" + format_table(table, ("arm", "n_draws", "agreement_mean", "excess_cost_mean",
                                         "cost_rel_mean", "train_regret_mean")))
    log.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

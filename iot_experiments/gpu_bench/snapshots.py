"""
CN: 可复用的「冻结 master 快照」：把循环在若干点（早/中/末）产生的边集 F 及其 HiGHS 精确解存盘，
    任何后续想法（惩罚项、新求解器、新 tie-break、剪枝）都能离线在这些真实 master 上测试，无需重跑循环。
EN: Reusable "frozen master snapshots": save the edge sets F produced by the loop at several points
    (early/half/last) together with their exact HiGHS solutions, so any future idea (penalty,
    new solver, new tie-break, pruning) can be tested offline on real masters without re-running.

CN: 真值方案由 **HELLO-OT** 生成（不是 POT）：替换掉 `loop_diag.build_problem` 的 POT 路径。
EN: The observed plan is generated by **HELLO-OT** (not POT), replacing `loop_diag.build_problem`.

用法 / EN: usage:
    python -m iot_experiments.gpu_bench.snapshots save --n 1600 --seed 0 --family diagonal
    python -m iot_experiments.gpu_bench.snapshots save --n 1600 3200 6400 --seeds 0 1 2 --families diagonal quadratic
文件 / files: out/snapshots/<run_id>.npz  (+ .json 记录元数据/δ/耗时)
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
from scipy import sparse

_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from iot import EdgeSet, InverseOTProblem, LinearMasterSolver, CuPdlpxMasterSolver  # noqa: E402
from iot_experiments.core.families import FamilySpec, build_family  # noqa: E402
from iot_experiments.core.marginals import marginal_spec  # noqa: E402
from iot_experiments.core.runner import _hello_plan  # noqa: E402
from iot_experiments.gpu_bench.loop_diag import RecordingSolver, edge_hash, run_loop  # noqa: E402

_OUT = _REPO_ROOT / "iot_experiments" / "gpu_bench" / "out" / "snapshots"


def build_hello_problem(*, family: str, point_dimension: int, marginal: str, n: int, seed: int,
                        plan_iters: int = 200, device: str = "auto") -> InverseOTProblem:
    """CN: 用 HELLO-OT 生成真值 π̂ 的实例（线性内存，替代 POT）。EN: HELLO-based instance (not POT)."""
    rng = np.random.default_rng(int(seed))
    features, theta_set, theta_star = build_family(
        FamilySpec(family, point_dimension=int(point_dimension)), rng, int(n), int(n)
    )
    a = marginal_spec(marginal).weights(int(n))
    b = marginal_spec(marginal).weights(int(n))
    plan, _u, _v = _hello_plan(features, theta_star, a, b, device=str(device), max_iterations=int(plan_iters))
    return InverseOTProblem(features=features, theta_set=theta_set, plan=sparse.csr_matrix(plan))


def save_one(*, family: str, point_dimension: int, marginal: str, n: int, seed: int,
             loop_solver: str, max_iterations: int, device: str) -> dict[str, object]:
    """CN: 跑一次循环，保存 early/half/last 三个 F 及其 HiGHS 精确解。EN: Run once; save early/half/last F + HiGHS solves."""
    problem = build_hello_problem(
        family=family, point_dimension=int(point_dimension), marginal=marginal, n=int(n), seed=int(seed),
        device=str(device),
    )
    inner = (CuPdlpxMasterSolver(params={"time_sec_limit": 60.0}) if loop_solver == "cupdlpx"
             else LinearMasterSolver(random_seed=int(seed)))
    result, rec, log = run_loop(
        problem, inner=inner, prune=(loop_solver != "cupdlpx"), hysteresis=(loop_solver != "cupdlpx"),
        max_iterations=int(max_iterations), scan_backend="numpy",
    )
    k = int(result.n_iterations)
    points = {"early": 0, "half": max(0, (k - 1) // 2), "last": k - 1}
    run_id = f"{family}__{marginal}__n{n}_seed{seed}_{loop_solver}"
    arrays: dict[str, np.ndarray] = {
        "support_rows": problem.support_rows, "support_cols": problem.support_cols,
        "source_dual": rec.solutions[-1].source_dual if rec.solutions else np.zeros(0),
    }
    meta: dict[str, object] = {
        "run_id": run_id, "family": family, "marginal": marginal, "n": int(n), "seed": int(seed),
        "point_dimension": int(point_dimension), "loop_solver": loop_solver, "K": int(problem.n_features),
        "iterations": k, "converged": bool(result.converged), "final_delta": float(result.delta),
        "final_F": int(result.support_size), "F_hashes": rec.hashes, "points": {},
    }
    for name, idx in points.items():
        F = rec.edge_sets[int(idx)]
        t0 = time.perf_counter()
        hs = LinearMasterSolver(random_seed=int(seed)).solve(problem, F, tie_break="none")
        t_hs = time.perf_counter() - t0
        arrays[f"{name}_F_rows"] = np.asarray(F.rows, dtype=np.int64)
        arrays[f"{name}_F_cols"] = np.asarray(F.cols, dtype=np.int64)
        arrays[f"{name}_theta"] = np.asarray(hs.theta, dtype=np.float64)
        arrays[f"{name}_src_dual"] = np.asarray(hs.source_dual, dtype=np.float64)
        arrays[f"{name}_tgt_dual"] = np.asarray(hs.target_dual, dtype=np.float64)
        meta["points"][name] = {  # type: ignore[index]
            "iteration": int(idx) + 1, "F_size": int(F.size), "F_hash": rec.hashes[int(idx)],
            "loop_delta": float(log[int(idx)]["delta"]), "loop_maxviol": float(log[int(idx)]["max_violation"]),
            "highs_delta": float(hs.delta), "highs_solve_seconds": t_hs,
        }
        print(f"[snap] {run_id} {name}: |F|={F.size} loop_delta={log[int(idx)]['delta']:.4g} "
              f"highs_delta={hs.delta:.4g} ({t_hs:.2f}s)", flush=True)
    _OUT.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(_OUT / f"{run_id}.npz", **arrays)
    (_OUT / f"{run_id}.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    return meta


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description="frozen master snapshots")
    p.add_argument("mode", choices=("save",))
    p.add_argument("--n", type=int, nargs="+", default=[1600])
    p.add_argument("--families", nargs="+", default=["diagonal"])
    p.add_argument("--seeds", type=int, nargs="+", default=[0])
    p.add_argument("--point-dimension", type=int, default=8)
    p.add_argument("--marginal", default="gmm_floored")
    p.add_argument("--loop-solver", default="cupdlpx", choices=("cupdlpx", "highs"))
    p.add_argument("--max-iterations", type=int, default=60)
    p.add_argument("--device", default="auto")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    for family in args.families:
        for n in args.n:
            for seed in args.seeds:
                save_one(family=str(family), point_dimension=int(args.point_dimension),
                         marginal=str(args.marginal), n=int(n), seed=int(seed),
                         loop_solver=str(args.loop_solver), max_iterations=int(args.max_iterations),
                         device=str(args.device))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

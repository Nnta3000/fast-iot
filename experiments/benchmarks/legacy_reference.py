"""
EN: **Frozen reference generator -- a test fixture, not part of the pipeline.**

    `tests/iot_benchmark_test.py` asserts that the current instance generator
    (`experiments/benchmarks/instances.build_instance`) reproduces, seed for seed, the generator that the
    old benchmark records were produced with. That assertion is the only thing keeping old records comparable
    after the generator was rewritten and moved.

    The original lived in `experiments/legacy/scratch/common.py`, which `.gitignore` excludes wholesale.
    A tracked test must not import an ignored path -- it then passes only on a machine where the ignored tree
    happens to survive and fails in a fresh clone or a fresh worktree (this is how the defect surfaced). So the
    generator is frozen here, byte for byte, and nothing else imports it.

    **Do not edit this file to make a new test pass.** If the current generator changes on purpose, the
    golden test is what should change; this copy is the historical record.

    CN: **冻结的参考生成器——测试夹具，不是流水线的一部分。** 基准测试用它逐位核对当前生成器复现旧记录所用的
        生成器。原件在 `legacy/scratch/` 里，而 `.gitignore` 整目录忽略它；被跟踪的测试不能 import 被忽略
        的路径，否则只在还留着该目录的机器上通过。因此把生成器原样冻结在这里，除此之外无人使用。
        **不要为了通过新测试而修改本文件**：如果当前生成器是有意改变的，该改的是基准测试，这里只是历史记录。
"""

from __future__ import annotations

import numpy as np
import ot
from scipy import sparse

from iot import DiagonalWeightFeatures, InverseOTProblem, SimplexTheta, dense_cost_matrix

__all__ = ["build_problem"]


def build_problem(
    *,
    n: int,
    k: int,
    seed: int,
    mixing_strength: float = 0.0,
    num_itermax: int = 100_000,
) -> tuple[InverseOTProblem, np.ndarray]:
    """
    EN: the historical generator: a diagonal-weight instance with a known `theta_star`, plan from POT.
        `num_itermax` is forwarded to `ot.emd`; at n >= 3200 POT's default cap returns a non-optimal plan,
        which would make the master genuinely infeasible.
    CN: 历史生成器：已知 `theta_star` 的对角权重实例，方案由 POT 求解。`num_itermax` 透传给 `ot.emd`；
        n >= 3200 时默认上限会返回非最优方案，使 master 真的不可行。
    """
    rng = np.random.default_rng(int(seed))
    theta_set = SimplexTheta(int(k))
    theta_star = theta_set.sample(rng)
    source = rng.normal(size=(int(n), int(k)))
    target = rng.normal(size=(int(n), int(k)))
    if float(mixing_strength) > 0.0:
        lower = np.tril(rng.standard_normal((int(k), int(k))), -1)
        mix = np.eye(int(k)) + float(mixing_strength) * lower
        source = source @ mix
        lower = np.tril(rng.standard_normal((int(k), int(k))), -1)
        mix = np.eye(int(k)) + float(mixing_strength) * lower
        target = target @ mix
    features = DiagonalWeightFeatures(source, target)
    cost = dense_cost_matrix(features, theta_star)
    mass = np.full(int(n), 1.0 / float(n))
    plan = ot.emd(mass, mass, cost, numItermax=int(num_itermax))
    problem = InverseOTProblem(features=features, theta_set=theta_set, plan=sparse.csr_matrix(plan))
    return problem, theta_star
